/**
 * Regenerates src/lib/cloudflareIps.ts from Cloudflare's published edge ranges.
 *
 *   npm run cloudflare:ips            # dry run: prints the ranges and whether they changed
 *   npm run cloudflare:ips -- --write # rewrites src/lib/cloudflareIps.ts (review + commit the diff)
 *
 * The CMS webhook fence (src/lib/clientIp.ts) trusts `CF-Connecting-IP` only from a peer inside these
 * ranges, so a stale list fails CLOSED (a new Cloudflare edge's deliveries are refused with 401 and the
 * CMS retries; the nightly list still carries every account). Run it when Cloudflare announces a change,
 * or every few months. Never fetched at runtime: the request path makes no outbound calls.
 * Zero dependencies (Node's fetch + net.BlockList). Refuses a response that is not a plain CIDR list.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { isIP } from 'node:net';
import path from 'node:path';

const SOURCES = {
  v4: 'https://www.cloudflare.com/ips-v4',
  v6: 'https://www.cloudflare.com/ips-v6',
} as const;
const TARGET = path.resolve(__dirname, '..', 'src', 'lib', 'cloudflareIps.ts');

async function fetchList(url: string, family: 4 | 6): Promise<string[]> {
  const res = await fetch(url, { redirect: 'error', signal: AbortSignal.timeout(20_000) });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  const lines = (await res.text()).split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
  for (const l of lines) {
    const [net, bits, extra] = l.split('/');
    const max = family === 4 ? 32 : 128;
    if (extra !== undefined || isIP(net) !== family || !/^\d{1,3}$/.test(bits ?? '') || Number(bits) > max) {
      throw new Error(`${url}: not a plain IPv${family} CIDR list — refusing to write`);
    }
  }
  // A truncated answer must never shrink the list silently (CLAUDE.md pattern 4).
  if (lines.length < (family === 4 ? 10 : 5)) throw new Error(`${url}: only ${lines.length} ranges — refusing`);
  return lines;
}

function render(v4: string[], v6: string[], date: string): string {
  const list = (xs: string[]) => xs.map((x) => `  '${x}',`).join('\n');
  return `/**
 * Cloudflare's published edge ranges — GENERATED by \`npm run cloudflare:ips\` (scripts/refresh-cloudflare-ips.ts).
 * Do not edit by hand; re-run the script and commit the diff. Never fetched at runtime.
 *
 * Source: ${SOURCES.v4} and ${SOURCES.v6}
 * Fetched: ${date}
 *
 * Used by src/lib/clientIp.ts: \`CF-Connecting-IP\` is trusted ONLY when the peer Railway saw is
 * inside these ranges (CMS webhook IP fence, docs/CMS_AUDIENCE_SYNC_DESIGN.md §5.1).
 */
export const CLOUDFLARE_IPS_FETCHED = '${date}';

export const CLOUDFLARE_IPV4: readonly string[] = [
${list(v4)}
];

export const CLOUDFLARE_IPV6: readonly string[] = [
${list(v6)}
];
`;
}

async function main(): Promise<void> {
  const [v4, v6] = await Promise.all([fetchList(SOURCES.v4, 4), fetchList(SOURCES.v6, 6)]);
  const current = readFileSync(TARGET, 'utf8');
  const date = new Date().toISOString().slice(0, 10);
  const next = render(v4, v6, date);
  const strip = (s: string) => s.replace(/Fetched: .*|CLOUDFLARE_IPS_FETCHED = '.*'/g, '');
  const changed = strip(next) !== strip(current);
  console.log(`IPv4 ranges: ${v4.length}\nIPv6 ranges: ${v6.length}\n${changed ? 'CHANGED since the committed list.' : 'Unchanged.'}`);
  if (process.argv.includes('--write')) {
    writeFileSync(TARGET, next);
    console.log(`Wrote ${path.relative(process.cwd(), TARGET)} — review the diff and commit it.`);
  } else if (changed) {
    console.log('Dry run. Re-run with --write to update the file.');
  }
}

main().catch((e: unknown) => {
  console.error(`refresh-cloudflare-ips failed: ${e instanceof Error ? e.message : 'unknown error'}`);
  process.exit(1);
});
